"""Rebuild teaching outlines from pinned Natural Earth public-domain data.
Outer rings only: small inland lakes do not invalidate a mountain/plateau answer.
These are generalized physical regions, not authoritative geological boundaries.
"""
import json, math, urllib.request
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
REV='ca96624a56bd078437bca8184e78163e5039ad19'
BASE=f'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/{REV}/geojson/'
def read(name):
 with urllib.request.urlopen(BASE+name+'.geojson',timeout=90) as r:return json.load(r)['features']
def distance(p,a,b):
 dx,dy=b[0]-a[0],b[1]-a[1];t=max(0,min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/(dx*dx+dy*dy or 1)))
 return math.hypot(p[0]-a[0]-t*dx,p[1]-a[1]-t*dy)
def simplify(p,tolerance=.04):
 if len(p)<3:return p
 d,i=max((distance(p[i],p[0],p[-1]),i) for i in range(1,len(p)-1))
 if d<=tolerance:return [p[0],p[-1]]
 return simplify(p[:i+1],tolerance)[:-1]+simplify(p[i:],tolerance)
def rings(f,tolerance=.04):
 g=f['geometry'];polys=[g['coordinates']] if g['type']=='Polygon' else g['coordinates']
 out=[]
 for poly in polys:
  ring=poly[0];s=simplify(ring,tolerance)
  if len(s)<4:s=ring
  out.append([[round(x,4),round(y,4)] for x,y,*_ in s])
 return out
# Names may be prefixed with the Natural Earth layer: marine:, lake:. Default: geography regions.
LAYERS={'region':('ne_10m_geography_regions_polys','NAME',.04),'marine':('ne_10m_geography_marine_polys','name',.04),'lake':('ne_10m_lakes','name',.005)}
cache={}
def features(layer):
 if layer not in cache:cache[layer]=read(LAYERS[layer][0])
 return cache[layer]
mapping=json.loads((ROOT/'sources/region-mapping.json').read_text());regions={}
for key,names in mapping.items():
 regions[key]=[]
 for full in names:
  layer,name=full.split(':',1) if ':' in full else ('region',full);_,field,tol=LAYERS[layer]
  matches=[f for f in features(layer) if f['properties'].get(field)==name]
  assert matches,(key,full)
  regions[key]+=[r for f in matches for r in rings(f,tol)]
(ROOT/'regions-natural-earth.js').write_text('// Generated by scripts/regions.py. Natural Earth, public domain; see sources/README.md.\nexport const NATURAL_REGIONS = '+json.dumps(regions,separators=(',',':'))+';\n')
print(len(regions),'regions,',sum(len(r) for v in regions.values() for r in v),'vertices')
